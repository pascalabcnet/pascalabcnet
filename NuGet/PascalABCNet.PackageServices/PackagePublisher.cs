using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace PascalABCNet.PackageServices;

/// <summary>Creates a framework-dependent .NET 10 folder without a NuGet cache dependency.</summary>
public static class PackagePublisher
{
    public static string Publish(string executablePath, string sourceFilePath, string runtimeDirectory)
    {
        string executable = Path.GetFullPath(executablePath);
        string source = Path.GetFullPath(sourceFilePath);
        string runtime = Path.GetFullPath(runtimeDirectory);
        string sourceDirectory = Path.GetDirectoryName(source)!;
        string destination = Path.Combine(sourceDirectory, "publish", Path.GetFileNameWithoutExtension(source));
        string publishRoot = Path.GetDirectoryName(destination)!;
        if (Directory.Exists(publishRoot) &&
            (File.GetAttributes(publishRoot) & FileAttributes.ReparsePoint) != 0)
            throw new IOException("Publish directory is a symbolic link: " + publishRoot);
        string runtimeConfig = Path.ChangeExtension(executable, ".runtimeconfig.json");
        if (!File.Exists(executable) || !File.Exists(runtimeConfig))
            throw new FileNotFoundException("The compiled program and runtimeconfig.json are required for publishing.");

        // Build everything in a sibling directory. A failed publish must not change the previous result.
        string staging = destination + ".staging-" + Guid.NewGuid().ToString("N");
        Directory.CreateDirectory(staging);
        try
        {
            var copied = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
            Copy(executable, staging, copied);

            var config = JsonNode.Parse(File.ReadAllText(runtimeConfig)) as JsonObject
                ?? throw new InvalidDataException("Invalid runtimeconfig.json: " + runtimeConfig);
            var options = config["runtimeOptions"] as JsonObject
                ?? throw new InvalidDataException("runtimeOptions is missing: " + runtimeConfig);
            var probing = options["additionalProbingPaths"] as JsonArray;
            options.Remove("additionalProbingPaths");
            File.WriteAllText(Path.Combine(staging, Path.GetFileName(runtimeConfig)),
                config.ToJsonString(new System.Text.Json.JsonSerializerOptions { WriteIndented = true }));

            string depsPath = Path.ChangeExtension(executable, ".deps.json");
            if (File.Exists(depsPath))
                CopyNuGetAssemblies(depsPath, probing, staging, copied);

            // The generated NuGet deps file points to package directories. A published
            // application instead probes its own directory for these managed assemblies.
            // Do not copy that deps file or the original cache probing paths.
            var pending = new Queue<string>(copied.Values.Where(IsManagedAssembly));
            var scanned = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
            while (pending.Count != 0)
            {
                string assembly = pending.Dequeue();
                if (!scanned.Add(assembly)) continue;
                foreach (string name in GetReferences(assembly))
                {
                    if (copied.ContainsKey(name + ".dll")) continue;
                    string? dependency = new[] {
                        Path.Combine(Path.GetDirectoryName(executable)!, name + ".dll"),
                        Path.Combine(sourceDirectory, name + ".dll"),
                        Path.Combine(runtime, name + ".dll")
                    }.FirstOrDefault(File.Exists);
                    if (dependency == null) continue; // Framework assemblies resolve from the installed runtime.
                    Copy(dependency, staging, copied);
                    pending.Enqueue(dependency);
                }
            }

            ReplacePublishedDirectory(destination, staging);
            return destination;
        }
        finally
        {
            if (Directory.Exists(staging)) Directory.Delete(staging, recursive: true);
        }
    }

    private static void CopyNuGetAssemblies(string depsPath, JsonArray? probing,
        string staging, Dictionary<string, string> copied)
    {
        using var document = JsonDocument.Parse(File.ReadAllText(depsPath));
        JsonElement root = document.RootElement;
        if (!root.TryGetProperty("pascalABCNET", out var marker) ||
            !marker.TryGetProperty("generatedNuGetManifest", out var generated) ||
            generated.ValueKind != JsonValueKind.True)
            throw new InvalidDataException("The deps file was not generated by PascalABC.NET: " + depsPath);
        var libraries = root.GetProperty("libraries");
        var targets = root.GetProperty("targets");
        foreach (var target in targets.EnumerateObject())
        foreach (var package in target.Value.EnumerateObject())
        {
            string packagePath = libraries.GetProperty(package.Name).GetProperty("path").GetString()!;
            foreach (var asset in package.Value.GetProperty("runtime").EnumerateObject())
            {
                if (!asset.Name.EndsWith(".dll", StringComparison.OrdinalIgnoreCase))
                    continue;
                string? source = null;
                if (probing != null)
                    foreach (var cache in probing)
                    {
                        string cachePath = Path.GetFullPath((string)cache!);
                        string rootPath = Path.GetFullPath(Path.Combine(cachePath, packagePath));
                        if (!Inside(cachePath, rootPath))
                            throw new InvalidDataException("NuGet package escapes its cache: " + packagePath);
                        string candidate = Path.GetFullPath(Path.Combine(rootPath, asset.Name));
                        if (!Inside(rootPath, candidate))
                            throw new InvalidDataException("NuGet asset escapes its package: " + asset.Name);
                        if (File.Exists(candidate)) { source = candidate; break; }
                    }
                if (source == null)
                    throw new FileNotFoundException("NuGet runtime asset is missing: " + package.Name + "/" + asset.Name);
                Copy(source, staging, copied);
            }
        }
    }

    private static void Copy(string source, string destination, Dictionary<string, string> copied)
    {
        string name = Path.GetFileName(source);
        if (copied.TryGetValue(name, out var previous))
        {
            if (!File.ReadAllBytes(previous).SequenceEqual(File.ReadAllBytes(source)))
                throw new InvalidDataException("Different dependencies have the same file name: " + name);
            return;
        }
        File.Copy(source, Path.Combine(destination, name));
        copied.Add(name, source);
    }

    private static bool IsManagedAssembly(string path)
    {
        try { using var file = File.OpenRead(path); using var pe = new PEReader(file); return pe.HasMetadata; }
        catch (BadImageFormatException) { return false; }
    }

    private static IEnumerable<string> GetReferences(string path)
    {
        using var file = File.OpenRead(path);
        using var pe = new PEReader(file);
        var metadata = pe.GetMetadataReader();
        foreach (var handle in metadata.AssemblyReferences)
            yield return metadata.GetString(metadata.GetAssemblyReference(handle).Name);
    }

    private static bool Inside(string root, string path) =>
        Path.GetRelativePath(root, path) is var relative && relative != ".." &&
        !relative.StartsWith(".." + Path.DirectorySeparatorChar, StringComparison.Ordinal) &&
        !Path.IsPathRooted(relative);

    private static void ReplacePublishedDirectory(string destination, string staging)
    {
        if (!Directory.Exists(destination))
        {
            Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
            Directory.Move(staging, destination);
            return;
        }
        string programName = Path.GetFileName(destination);
        if (!File.Exists(Path.Combine(destination, programName + ".exe")) ||
            !File.Exists(Path.Combine(destination, programName + ".runtimeconfig.json")))
            throw new IOException("Publish destination is not a published program folder: " + destination);
        // Publishing replaces this program's output folder as a whole. Do not follow
        // junctions or symlinks when moving and removing the previous version.
        var pending = new Stack<string>();
        pending.Push(destination);
        while (pending.Count != 0)
        {
            string current = pending.Pop();
            if ((File.GetAttributes(current) & FileAttributes.ReparsePoint) != 0)
                throw new IOException("Publish destination contains a symbolic link: " + current);
            foreach (string entry in Directory.EnumerateFileSystemEntries(current))
            {
                var attributes = File.GetAttributes(entry);
                if ((attributes & FileAttributes.ReparsePoint) != 0)
                    throw new IOException("Publish destination contains a symbolic link: " + entry);
                if ((attributes & FileAttributes.Directory) != 0) pending.Push(entry);
            }
        }
        string backup = destination + ".previous-" + Guid.NewGuid().ToString("N");
        Directory.Move(destination, backup);
        try { Directory.Move(staging, destination); }
        catch { Directory.Move(backup, destination); throw; }
        Directory.Delete(backup, recursive: true);
    }
}
